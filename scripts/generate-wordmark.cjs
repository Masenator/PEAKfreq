/**
 * Generates src/components/wordmark-paths.ts from the Archivo glyphs in scripts/fonts.
 *
 *   node scripts/generate-wordmark.cjs
 *
 * PEAK: Archivo Condensed Black, intersected with a mountain-ridge polygon so the
 *       letters' top edge is a ridgeline (real geometry, so it can be outlined).
 * freq: Archivo Light Italic, with a pulse line trailing off the end of the q.
 *
 * Fonts: Archivo by Omnibus-Type, SIL Open Font License 1.1 (subset to "PEAKfreq").
 */
const fs = require("fs");
const path = require("path");
const opentype = require("opentype.js");
const PolyBool = require("polybooljs");

const FONTS = path.join(__dirname, "fonts");
const peakFont = opentype.loadSync(path.join(FONTS, "archivo-condensed-black.ttf"));
const freqFont = opentype.loadSync(path.join(FONTS, "archivo-light-italic.ttf"));
const SIZE = 100;

/** Flatten an opentype path into closed polygons (curves sampled). */
function toPolygons(p) {
  const polys = [];
  let cur = [];
  let x = 0;
  let y = 0;
  const STEPS = 10;
  for (const c of p.commands) {
    if (c.type === "M") {
      if (cur.length) polys.push(cur);
      cur = [[c.x, c.y]];
    } else if (c.type === "L") {
      cur.push([c.x, c.y]);
    } else if (c.type === "Q") {
      for (let i = 1; i <= STEPS; i++) {
        const t = i / STEPS;
        const a = (1 - t) ** 2, b = 2 * (1 - t) * t, d = t * t;
        cur.push([a * x + b * c.x1 + d * c.x, a * y + b * c.y1 + d * c.y]);
      }
    } else if (c.type === "C") {
      for (let i = 1; i <= STEPS; i++) {
        const t = i / STEPS;
        const a = (1 - t) ** 3, b = 3 * (1 - t) ** 2 * t, e = 3 * (1 - t) * t * t, d = t ** 3;
        cur.push([a * x + b * c.x1 + e * c.x2 + d * c.x, a * y + b * c.y1 + e * c.y2 + d * c.y]);
      }
    } else if (c.type === "Z") {
      if (cur.length) polys.push(cur);
      cur = [];
      continue;
    }
    x = c.x;
    y = c.y;
  }
  if (cur.length) polys.push(cur);
  return polys;
}

const f1 = (n) => Math.round(n * 10) / 10;
const polyToD = (regions) =>
  regions.map((r) => "M" + r.map(([px, py]) => `${f1(px)} ${f1(py)}`).join("L") + "Z").join("");

/* ── PEAK with ridgeline top ── */
let x = 0;
let peakRegions = [];
const ridge = [
  [-2, -50], [12, -61], [20, -57.5], [40, -66.5], [56, -58], [68, -63.5], [84, -60], [98, -64.5],
  [110, -58], [142.5, -71], [174, -56], [190, -63], [200, -59], [216, -67.5], [232, -54], [240, -46],
];
const ridgePoly = { regions: [[[-5, 20], ...ridge, [245, 20]]], inverted: false };
for (const ch of "PEAK") {
  const g = peakFont.charToGlyph(ch);
  const shape = { regions: toPolygons(g.getPath(x, 0, SIZE)), inverted: false };
  const cut = PolyBool.intersect(shape, ridgePoly);
  peakRegions = peakRegions.concat(cut.regions);
  x += (g.advanceWidth * SIZE) / peakFont.unitsPerEm;
}
const PEAK_D = polyToD(peakRegions);

/* ── freq ── */
const GX = 250;
x = GX;
const freqPaths = [];
let qPolys = [];
for (const ch of "freq") {
  const g = freqFont.charToGlyph(ch);
  const p = g.getPath(x, 0, SIZE);
  freqPaths.push(p.toPathData(1));
  if (ch === "q") qPolys = toPolygons(p);
  x += (g.advanceWidth * SIZE) / freqFont.unitsPerEm;
}
const FREQ_D = freqPaths.join("");

/** Rightmost x of the q outline around a given y (the q's stem edge). */
function rightEdgeAt(yTarget) {
  let best = -Infinity;
  for (const poly of qPolys) {
    for (let i = 0; i < poly.length; i++) {
      const [ax, ay] = poly[i];
      const [bx, by] = poly[(i + 1) % poly.length];
      if ((ay - yTarget) * (by - yTarget) <= 0 && ay !== by) {
        const t = (yTarget - ay) / (by - ay);
        best = Math.max(best, ax + t * (bx - ax));
      }
    }
  }
  return best;
}

// Pulse leaves the q's stem at mid x-height and trails off to the right.
const PY = -27;
const qx = rightEdgeAt(PY) - 2.5;
const pts = [
  [qx, PY], [qx + 10, PY], [qx + 15, PY - 10], [qx + 20, PY + 4], [qx + 26, PY], [qx + 31, PY],
  [qx + 37, PY - 44], [qx + 45, PY + 30], [qx + 51, PY], [qx + 66, PY],
];
const PULSE_D = "M" + pts.map(([px, py]) => `${f1(px)},${f1(py)}`).join("L");
const right = qx + 66;

const PAD = 11; // room for PEAK's outline
const minX = -PAD - 2;
const minY = -84;
const w = Math.ceil(right + 4 - minX);
const h = 114;
const out = `/* Generated by scripts/generate-wordmark.cjs. Do not edit by hand. */
export const WM_VIEWBOX = "${minX} ${minY} ${w} ${h}";
export const WM_ASPECT = ${(w / h).toFixed(4)};
/** PEAK, already cut to the ridgeline. */
export const WM_PEAK = "${PEAK_D}";
export const WM_FREQ = "${FREQ_D}";
/** Pulse trailing off the q. */
export const WM_PULSE = "${PULSE_D}";
export const WM_GRAD_X = [${GX}, ${f1(right)}] as const;
`;
const dest = path.join(__dirname, "..", "src", "components", "wordmark-paths.ts");
fs.writeFileSync(dest, out);
console.log(`wrote ${dest} (${out.length} bytes); q edge ${f1(qx)}; viewBox ${minX} ${minY} ${w} ${h}`);
